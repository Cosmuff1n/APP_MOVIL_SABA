-- El id aquí es el identificador REMOTO; Android mantiene su id local Room.
CREATE TABLE parkings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    address VARCHAR(255) NOT NULL DEFAULT '',
    commune VARCHAR(120) NOT NULL DEFAULT '',
    total_spaces INTEGER NOT NULL DEFAULT 0,
    free_spaces INTEGER NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    revision BIGINT NOT NULL DEFAULT 0,
    updated_at BIGINT NOT NULL,
    CONSTRAINT ck_parkings_name_nonempty CHECK (length(trim(name)) > 0),
    CONSTRAINT ck_parkings_spaces CHECK (
        total_spaces >= 0 AND free_spaces >= 0 AND free_spaces <= total_spaces
    )
);
CREATE INDEX idx_parkings_name ON parkings (name);
