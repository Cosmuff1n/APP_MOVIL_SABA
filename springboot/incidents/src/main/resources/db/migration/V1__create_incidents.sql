-- IDs de parking y service: referencias remotas, SIN claves foráneas entre microservicios.
-- No hay binarios ni URI locales de Android: la carga de evidencia está pendiente de contrato.
CREATE TABLE incidents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_code VARCHAR(60) NOT NULL UNIQUE,
    parking_id BIGINT NOT NULL,
    service_id BIGINT NOT NULL,
    reporter_name VARCHAR(150) NOT NULL DEFAULT '',
    failure_type VARCHAR(120) NOT NULL,
    description VARCHAR(240) NOT NULL,
    status VARCHAR(40) NOT NULL,
    reported_at BIGINT NOT NULL,
    is_resolved BOOLEAN NOT NULL DEFAULT FALSE,
    resolved_by_name VARCHAR(150),
    resolution_description VARCHAR(300),
    resolved_at BIGINT,
    revision BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX idx_incidents_parking_id ON incidents(parking_id);
CREATE INDEX idx_incidents_service_id ON incidents(service_id);
CREATE INDEX idx_incidents_reported_at ON incidents(reported_at DESC);
